#   Strings
firstName = "Vishwas"
food = "pizza"
email = "vishwas@gmail.com"
print(f"Hello {firstName}")
print(f"You like {food}")
print(f"Your email is {email}")

#   Integers
age = 18
print(f"You are {age} years old")

#   Float
price = 10.99
print(f"Price of your item is ${price}")

#   Boolean
isStudent = True
print(f"Are you a student ? : {isStudent}")